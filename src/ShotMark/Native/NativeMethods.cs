        /// <summary>Hides a window from screenshots and recordings (Windows 10 2004+), so our own UI never shows up in captures.</summary>
        public static void ExcludeFromCapture(System.Windows.Window window)
        {
            try
            {
                var hwnd = new System.Windows.Interop.WindowInteropHelper(window).EnsureHandle();
                SetWindowDisplayAffinity(hwnd, WDA_EXCLUDEFROMCAPTURE);
            }
            catch (Exception)
            {
            }
        }

        /// <summary>Lets mouse clicks pass through a window.</summary>
        public static void MakeClickThrough(System.Windows.Window window)
        {
            var hwnd = new System.Windows.Interop.WindowInteropHelper(window).EnsureHandle();
            long ex = GetWindowLongPtr(hwnd, GWL_EXSTYLE).ToInt64();
            SetWindowLongPtr(hwnd, GWL_EXSTYLE, new IntPtr(ex | WS_EX_TRANSPARENT | WS_EX_LAYERED | WS_EX_TOOLWINDOW | WS_EX_NOACTIVATE));
        }

        /// <summary>Asks Windows 10 (20H1+) / 11 to draw a dark title bar for this window.</summary>
        public static void UseDarkTitleBar(System.Windows.Window window)
        {
            try
            {
                var hwnd = new System.Windows.Interop.WindowInteropHelper(window).EnsureHandle();
                int on = 1;
                DwmSetWindowAttribute(hwnd, DWMWA_USE_IMMERSIVE_DARK_MODE, ref on, sizeof(int));
            }
            catch (Exception)
            {
                // Older Windows: keep the default title bar.
            }
        }

